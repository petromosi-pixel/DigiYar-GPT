function stats(nodes, depth = 1, out = { nodes: 0, leaves: 0, maxDepth: 0 }) {
  for (const x of nodes) { out.nodes++; out.maxDepth = Math.max(out.maxDepth, depth); if (!x.children.length) out.leaves++; else stats(x.children, depth + 1, out); }
  return out;
}


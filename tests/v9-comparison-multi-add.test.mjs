import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const values=new Map();
const listeners={};
const localStorage={getItem(k){return values.get(k)||null;},setItem(k,v){values.set(k,String(v));},removeItem(k){values.delete(k);}};
const window={addEventListener(name,fn){listeners[name]=fn;},dispatchEvent(){}};
const context={window,localStorage,Date,JSON,console,CustomEvent:function(type,init){this.type=type;this.detail=init&&init.detail;}};
vm.runInNewContext(fs.readFileSync('js/v8-product-result-source.js','utf8'),context);
const source=window.DigiYarV7ProductResultSource;
source.clearComparison();
const first={name:'گوشی سامسونگ A55',brand:'سامسونگ',model:'A55',store:'دیجی‌کالا',priceToman:18000000};
const second={name:'گوشی سامسونگ S23 FE',brand:'سامسونگ',model:'S23 FE',store:'تکنولایف',priceToman:24000000};
source.addComparisonProduct(first);
source.addComparisonProduct(second);
let picked=source.getComparisonProducts();
assert.equal(picked.length,2,'two products without upstream IDs must remain independently selectable');
assert.notEqual(picked[0].id,picked[1].id,'fallback product IDs must be unique');
source.addComparisonProduct({name:'گوشی سامسونگ A55',brand:'سامسونگ',model:'A55',store:'دیجی‌کالا',priceToman:18000000});
picked=source.getComparisonProducts();
assert.equal(picked.length,2,'adding the same product twice must not duplicate it');
source.removeComparisonProduct(picked[1].id);
assert.equal(source.getComparisonProducts().length,1,'individual comparison removal must work');
const assistant=fs.readFileSync('js/v9-hooshyar-assistant.js','utf8');
assert.match(assistant,/data-v9-add-index/,'result cards must use stable list indexes for add actions');
assert.match(assistant,/function productKey\(p\)\{return\[p&&p.name/,'assistant must compare canonical product identity, not ephemeral IDs');
const ui=fs.readFileSync('js/v8-comparison-ui.js','utf8');
assert.match(ui,/margin:2mm 0 0!important/,'comparison title/subtitle gap must be 2mm');
assert.match(ui,/data-v7-remove-id/,'each detailed comparison card must support independent removal');
assert.match(ui,/body\.v6-dark #v7ComparisonCard \.v7c-card-chevron/,'comparison toggle must be dark-mode aware');
console.log('V9 comparison multi-add and UI contracts: PASS');

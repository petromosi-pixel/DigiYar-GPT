import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const window={};
vm.runInNewContext(fs.readFileSync('js/v8-persian-language-dictionary.js','utf8'),{window,globalThis:window});
const lex=window.DigiYarPersianDictionary;
assert.ok(lex,'dictionary must be exposed');
for(const [q,id] of [['پادری','doormat'],['فرش جلوی در','doormat'],['قالیچه ورودی','doormat'],['مبل','sofa'],['مبلمان','sofa'],['کاناپه','sofa'],['لپتاپ','laptop'],['تلفن همراه','mobile-phone'],['ایر فرایر','air-fryer'],['لپ‌تاپ گیمینگ','laptop'],['گوشی دوربین‌دار','mobile-phone'],['یخچال ساید','refrigerator'],['لباسشور','washing-machine'],['مبل‌شوی','carpet-cleaner'],['مودم اینترنت','router'],['موس بی‌سیم','computer-mouse'],['چمدون','suitcase']])assert.ok(lex.resolve(q).some(x=>x.id===id),q);
assert.ok(lex.expand('مبل').includes('مبلمان'));
assert.ok(lex.resolve('یه لپ‌تاپ گیمینگ واسه بازی می‌خوام').some(x=>x.id==='laptop'));
assert.ok(lex.resolve('یه یخچال ساید برای خونه').some(x=>x.id==='refrigerator'));
assert.ok(lex.resolve('لباسشویی درب از جلو').some(x=>x.id==='washing-machine'));
assert.ok(lex.resolve('یه مبل‌شوی برای تمیز کردن مبل').some(x=>x.id==='carpet-cleaner'));
assert.equal(lex.version,'1.3.0-persian-commerce-ontology');
assert.ok(lex.getEntries().every(entry=>entry.domains&&entry.domains.length>0),'Every commerce concept must map to at least one merchant domain');
assert.equal(lex.getEntries().length,126,'dictionary should expose the expanded commerce vocabulary');
assert.equal(lex.canonicalize('من یه فرش جلوی در می‌خوام'),'من یه پادری می خوام');
assert.ok(lex.lookup('مودم وای‌فای').some(x=>x.id==='router'));
assert.ok(lex.lookup('کارتریج پرینتر').some(x=>x.id==='printer-supplies'));
assert.ok(lex.lookup('پادری حمام').some(x=>x.id==='bath-mat'));
assert.ok(lex.lookup('سشوار مو').some(x=>x.id==='hair-dryer'));
assert.deepEqual(Array.from(lex.expandDetailed('سشوار مو').canonicalTerms),['سشوار']);
assert.ok(!lex.lookup('پادری').some(x=>x.id==='carpet'),'doormat must not collapse into generic carpet');
assert.ok(lex.matchProduct('پادری',{name:'فرش کوچک ورودی مدل ساده'}).some(x=>x.id==='doormat'));
assert.equal(lex.resolve('عبارت کاملاً نامرتبط').length,0);
console.log('DigiYar Persian commerce dictionary: PASS');
